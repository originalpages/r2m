func TestParseGitHubSpec(t *testing.T) {
	ok := map[string]string{
		"foo/bar":                             "https://github.com/foo/bar.git",
		"foo/bar.git":                         "https://github.com/foo/bar.git",
		"https://github.com/foo/bar":          "https://github.com/foo/bar.git",
		"https://www.github.com/foo/bar.git/": "https://github.com/foo/bar.git",
		"foo/bar.js":                          "https://github.com/foo/bar.js.git",
	}
	for in, want := range ok {
		g, found := ParseGitHubSpec(in)
		if !found || g.URL != want {
			t.Errorf("%q -> %+v %v, want %s", in, g, found, want)
		}
	}
	for _, in := range []string{"", "foo", "../x", "a/../b", "-x/y", "http://github.com/a/b", "https://evil.com/a/b", "a/b/c", "foo/..", "--upload-pack=x/y"} {
		if _, found := ParseGitHubSpec(in); found {
			t.Errorf("%q should be rejected", in)
		}
	}
}

func TestUpdateMarkerBlock(t *testing.T) {
	const S, E = "<!-- r2m:start -->", "<!-- r2m:end -->"
	got := UpdateMarkerBlock("# T\n\n"+S+"\nold\n"+E+"\n\nfooter\n", "flowchart LR\n  a-->b")
	want := "# T\n\n" + S + "\n```mermaid\nflowchart LR\n  a-->b\n```\n" + E + "\n\nfooter\n"
	if got != want {
		t.Fatalf("got %q want %q", got, want)
	}
	if got := UpdateMarkerBlock("# T\n", "graph TD"); got != "# T\n\n"+S+"\n```mermaid\ngraph TD\n```\n"+E+"\n" {
		t.Fatalf("append: %q", got)
	}
	once := UpdateMarkerBlock("# T\n", `a["$&"]`)
	if UpdateMarkerBlock(once, `a["$&"]`) != once {
		t.Fatal("not idempotent")
	}
	if !strings.Contains(UpdateMarkerBlock("", "x"), S) {
		t.Fatal("empty input")
	}
}

