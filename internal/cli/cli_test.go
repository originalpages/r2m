var sample = filepath.Join("..", "..", "testdata", "sample")

type result struct {
	code        int
	out, errOut string
	opened      string
}

func exec_(t *testing.T, interactive bool, stdin string, args ...string) result {
	t.Helper()
	var out, errOut bytes.Buffer
	var r result
	code := Run(args, IO{
		Stdin:       strings.NewReader(stdin),
		Stdout:      &out,
		Stderr:      &errOut,
		Interactive: interactive,
		ViewDir:     t.TempDir(),
		Open:        func(f string) bool { r.opened = f; return true },
	})
	r.code, r.out, r.errOut = code, out.String(), errOut.String()
	return r
}

