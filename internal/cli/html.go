package cli

import (
	_ "embed"
	"encoding/json"
	"html"
	"strconv"
	"strings"
)

// ProjectURL is shown in the footer of every page, picture and saved Markdown file.
const ProjectURL = "https://github.com/originalpages/r2m"

// The Mermaid library is embedded so the page works offline and from any location.
//
//go:embed assets/mermaid.min.js
var mermaidJS string

// Section is one diagram on the HTML page.
type Section struct {
	Title, Description, Source string
	// Empty, when set, replaces the diagram with this explanation (nothing to draw).
	Empty string
	// Variants, when set, lets the reader switch between several sources (focus folders).
	Variants []Variant
	Selected int
}

// Variant is one selectable version of a diagram.
type Variant struct {
	Label, Source string
}

// Page is everything needed to build the HTML view.
type Page struct {
	Name      string // project name (folder or owner/repo)
	SourceURL string // GitHub URL of the analysed project, if it came from GitHub
	Sections  []Section
}

const pageScript = `
mermaid.initialize({
  startOnLoad: false,
  securityLevel: 'strict',
  maxTextSize: 5000000,
  htmlLabels: false,
  flowchart: { htmlLabels: false }
});

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Draws title + diagram + footer into one standalone SVG (so PNG and SVG exports match).
function compose(section) {
  const svg = section.querySelector('.diagram svg');
  if (!svg) return null;
  const vb = svg.viewBox && svg.viewBox.baseVal;
  const box = svg.getBoundingClientRect();
  const w = Math.ceil((vb && vb.width) || box.width);
  const h = Math.ceil((vb && vb.height) || box.height);
  const clone = svg.cloneNode(true);
  clone.removeAttribute('style');
  clone.removeAttribute('max-width');
  clone.setAttribute('width', w);
  clone.setAttribute('height', h);
  const pad = 24, head = 64, foot = 44;
  const W = Math.max(w + pad * 2, 520), H = h + head + foot;
  clone.setAttribute('x', pad);
  clone.setAttribute('y', head);
  const d = document.body.dataset;
  const title = d.project + ' \u2013 ' + section.dataset.title;
  const foot1 = 'Generated by r2m \u00b7 ' + d.footer + (d.source ? ' \u00b7 Source: ' + d.source : '');
  const xml =
    '<svg xmlns="http://www.w3.org/2000/svg" width="' + W + '" height="' + H + '" viewBox="0 0 ' + W + ' ' + H + '">' +
    '<rect width="100%" height="100%" fill="#ffffff"/>' +
    '<text x="' + pad + '" y="38" font-family="system-ui, Segoe UI, Arial, sans-serif" font-size="22" font-weight="700" fill="#1f2328">' + esc(title) + '</text>' +
    new XMLSerializer().serializeToString(clone) +
    '<text x="' + pad + '" y="' + (H - 16) + '" font-family="system-ui, Segoe UI, Arial, sans-serif" font-size="13" fill="#656d76">' + esc(foot1) + '</text>' +
    '</svg>';
  return { xml, W, H, name: slug(d.project) + '-' + slug(section.dataset.title) };
}

function save(blobOrUrl, name) {
  const a = document.createElement('a');
  const url = typeof blobOrUrl === 'string' ? blobOrUrl : URL.createObjectURL(blobOrUrl);
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

function toPng(c) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const scale = Math.min(2, 16000 / Math.max(c.W, c.H));
      const canvas = document.createElement('canvas');
      canvas.width = Math.round(c.W * scale);
      canvas.height = Math.round(c.H * scale);
      const ctx = canvas.getContext('2d');
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
      canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('PNG export failed'))), 'image/png');
    };
    img.onerror = () => reject(new Error('Could not draw the picture'));
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(c.xml);
  });
}

async function exportSection(section, kind) {
  const c = compose(section);
  if (!c) return null;
  if (kind === 'svg') {
    const blob = new Blob([c.xml], { type: 'image/svg+xml' });
    return { blob, name: c.name + '.svg' };
  }
  return { blob: await toPng(c), name: c.name + '.png' };
}
window.r2mExport = exportSection; // also used by tests

// ---- zoom: small diagrams are scaled up (to 175%) to use the width; huge ones fit down to 40% ----
const MIN_AUTO_ZOOM = 0.4; // huge graphs fit the width down to 40%, then scroll; zoom in for detail
const MAX_AUTO_ZOOM = 1.75;
const zoom = new WeakMap(); // section -> { z, manual }

function natural(section) {
  const svg = section.querySelector('.diagram svg');
  if (!svg) return null;
  const vb = svg.viewBox && svg.viewBox.baseVal;
  const box = svg.getBoundingClientRect();
  return { svg, w: (vb && vb.width) || box.width, h: (vb && vb.height) || box.height };
}

function applyZoom(section, z) {
  const n = natural(section);
  if (!n) return;
  n.svg.style.maxWidth = 'none';
  n.svg.style.width = Math.round(n.w * z) + 'px';
  n.svg.style.height = Math.round(n.h * z) + 'px';
  const s = zoom.get(section) || { manual: false };
  zoom.set(section, { z, manual: s.manual });
  const label = section.querySelector('.zoomlabel');
  if (label) label.textContent = Math.round(z * 100) + '%';
}

function fit(section) {
  const n = natural(section);
  if (!n) return;
  const avail = section.querySelector('.diagram').clientWidth - 34;
  applyZoom(section, Math.max(MIN_AUTO_ZOOM, Math.min(avail / n.w, MAX_AUTO_ZOOM)));
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch (e) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    let ok = false;
    try { ok = document.execCommand('copy'); } catch (_) {}
    ta.remove();
    return ok;
  }
}

function flash(btn, text) {
  const old = btn.dataset.label || (btn.dataset.label = btn.textContent);
  btn.textContent = text;
  setTimeout(() => (btn.textContent = old), 1500);
}

document.querySelectorAll('section').forEach((section) => {
  if (!section.querySelector('.diagram')) return;
  section.querySelectorAll('button[data-act]').forEach((btn) => {
    btn.addEventListener('click', async () => {
      const act = btn.dataset.act;
      try {
        if (act === 'copy') {
          const src = section.querySelector('details pre').textContent;
          flash(btn, (await copyText(src)) ? 'Copied!' : 'Copy failed');
        } else if (act === 'zoomin' || act === 'zoomout') {
          const s = zoom.get(section) || { z: 1 };
          applyZoom(section, Math.min(8, Math.max(0.1, s.z * (act === 'zoomin' ? 1.25 : 0.8))));
          zoom.set(section, { z: zoom.get(section).z, manual: true });
        } else if (act === 'fit') {
          fit(section);
          zoom.set(section, { z: zoom.get(section).z, manual: false });
        } else {
          const r = await exportSection(section, act);
          if (r) save(r.blob, r.name);
        }
      } catch (e) {
        alert('Something went wrong: ' + (e && e.message ? e.message : e));
      }
    });
  });
});

// ---- focus picker: switch a big graph to one folder in detail ----
document.querySelectorAll('select.variant').forEach((sel) => {
  const section = sel.closest('section');
  let sources = [];
  try { sources = JSON.parse(section.querySelector('script.variants').textContent); } catch (e) { return; }
  sel.addEventListener('change', async () => {
    sel.disabled = true;
    try {
      const { svg } = await mermaid.render('v' + Date.now(), sources[Number(sel.value)]);
      section.querySelector('.diagram').innerHTML = svg;
      section.querySelector('details pre').textContent = sources[Number(sel.value)];
      zoom.set(section, { z: 1, manual: false });
      fit(section);
    } catch (e) {
      alert('Could not draw this view: ' + (e && e.message ? e.message : e));
    }
    sel.disabled = false;
  });
});

let resizeTimer;
window.addEventListener('resize', () => {
  clearTimeout(resizeTimer);
  resizeTimer = setTimeout(() => {
    document.querySelectorAll('section').forEach((s) => {
      const st = zoom.get(s);
      if (st && !st.manual) fit(s);
    });
  }, 150);
});

mermaid.run({ querySelector: '.mermaid' }).then(() => {
  document.querySelectorAll('section').forEach(fit);
  document.body.dataset.ready = '1';
}).catch((e) => {
  document.querySelectorAll('button[data-act]').forEach((b) => (b.disabled = true));
  console.error(e);
});
`

// BuildHTML renders a self-contained page that draws the Mermaid sources in the browser,
// with buttons to save each diagram as a picture.
func BuildHTML(p Page) string {
	var body strings.Builder
	for _, s := range p.Sections {
		if s.Empty != "" {
			body.WriteString("<section data-title=\"" + html.EscapeString(s.Title) + "\">\n  <h2>" + html.EscapeString(s.Title) +
				"</h2>\n  <p>" + html.EscapeString(s.Description) + "</p>\n  <p class=\"empty\">" + html.EscapeString(s.Empty) + "</p>\n</section>\n")
			continue
		}
		src := html.EscapeString(s.Source)
		picker := ""
		if len(s.Variants) > 1 {
			var opts strings.Builder
			labels := make([]string, 0, len(s.Variants))
			sources := make([]string, 0, len(s.Variants))
			for i, v := range s.Variants {
				sel := ""
				if i == s.Selected {
					sel = " selected"
				}
				opts.WriteString("<option value=\"" + strconv.Itoa(i) + "\"" + sel + ">" + html.EscapeString(v.Label) + "</option>")
				labels = append(labels, v.Label)
				sources = append(sources, v.Source)
			}
			data, _ := json.Marshal(sources) // < > & are escaped as \u003c etc., safe inside <script>
			picker = "  <div class=\"picker\"><label>Show: <select class=\"variant\">" + opts.String() + "</select></label> " +
				"<span class=\"hint\">Big project: pick a folder to see its files in detail. Dashed boxes are other folders it connects to.</span></div>\n" +
				"  <script type=\"application/json\" class=\"variants\">" + string(data) + "</script>\n"
		}
		body.WriteString("<section data-title=\"" + html.EscapeString(s.Title) + "\">\n  <h2>" + html.EscapeString(s.Title) + "</h2>\n  <p>" +
			html.EscapeString(s.Description) + "</p>\n" + picker +
			"  <div class=\"actions\"><button data-act=\"png\">Save as picture (PNG)</button> <button data-act=\"svg\">Save as SVG</button> " +
			"<button data-act=\"copy\">Copy Mermaid source</button> " +
			"<span class=\"zoom\"><button data-act=\"zoomout\" title=\"Zoom out\">&minus;</button><span class=\"zoomlabel\">100%</span><button data-act=\"zoomin\" title=\"Zoom in\">+</button><button data-act=\"fit\">Fit</button></span></div>\n" +
			"  <div class=\"diagram\"><pre class=\"mermaid\">" + src + "</pre></div>\n" +
			"  <details><summary>Show Mermaid source</summary><pre>" + src + "</pre></details>\n</section>\n")
	}
	lib := strings.NewReplacer("</script", `<\/script`, "</SCRIPT", `<\/SCRIPT`).Replace(mermaidJS)
	name := html.EscapeString(p.Name)
	source := ""
	if p.SourceURL != "" {
		u := html.EscapeString(p.SourceURL)
		source = `<p class="sub">Source: <a href="` + u + `">` + u + `</a></p>` + "\n"
	}
	return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>` + name + ` - r2m</title>
<style>
  body { font: 16px/1.5 system-ui, sans-serif; max-width: 1800px; margin: 0 auto; padding: 24px; color: #1f2328; }
  h1 { margin-bottom: 4px; }
  .sub { color: #656d76; margin: 0; }
  a { color: #0969da; }
  section { margin: 32px 0; padding-top: 16px; border-top: 1px solid #d0d7de; }
  .picker { margin: 8px 0; display: flex; flex-wrap: wrap; gap: 12px; align-items: center; }
  select { font: inherit; padding: 4px 8px; border: 1px solid #d0d7de; border-radius: 6px; max-width: 100%; }
  .hint { color: #656d76; font-size: 14px; }
  .actions { margin: 8px 0; display: flex; flex-wrap: wrap; gap: 8px; align-items: center; }
  .zoom { display: inline-flex; gap: 4px; align-items: center; margin-left: auto; }
  .zoomlabel { min-width: 48px; text-align: center; color: #656d76; font-size: 14px; }
  button { font: inherit; padding: 4px 12px; border: 1px solid #d0d7de; border-radius: 6px; background: #f6f8fa; cursor: pointer; }
  button:hover { background: #eaeef2; }
  button:disabled { opacity: .5; cursor: default; }
  .diagram { overflow: auto; border: 1px solid #d0d7de; border-radius: 8px; padding: 16px; }
  details { margin-top: 12px; }
  .empty { padding: 16px; border: 1px dashed #d0d7de; border-radius: 8px; color: #656d76; }
  pre { white-space: pre-wrap; }
  footer { margin-top: 48px; padding-top: 16px; border-top: 1px solid #d0d7de; color: #656d76; font-size: 14px; }
</style>
</head>
<body data-project="` + name + `" data-footer="` + html.EscapeString(ProjectURL) + `" data-source="` + html.EscapeString(p.SourceURL) + `">
<h1>` + name + `</h1>
` + source + body.String() + `<footer>Generated by <a href="` + ProjectURL + `">r2m</a> &middot; <a href="` + ProjectURL + `">` + ProjectURL + `</a></footer>
<script>` + lib + `</script>
<script>` + pageScript + `</script>
</body>
</html>
`
}
